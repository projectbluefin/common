#!/usr/bin/env python3
"""Validate skill front matter and generate docs/skills/index.json from it.

Usage:
    python3 scripts/generate_skill_index.py --write   # regenerate index.json
    python3 scripts/generate_skill_index.py --check   # verify index.json is up to date (exit 1 if stale)

The catalog is validated against docs/skills/index.schema.json (JSON Schema
2020-12) before being written or compared; each skill must also have
name == id and stay under the line budget. This script is the only supported
way to produce index.json — do not hand-edit it.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date, datetime, timezone
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "docs" / "skills"
SCHEMA_PATH = SKILLS_DIR / "index.schema.json"
INDEX_PATH = SKILLS_DIR / "index.json"
SCHEMA_VERSION = "1.0"
MAX_LINES_SOFT = 200
MAX_LINES_HARD = 500

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)

# On-device agent bundle shipped read-only into every image. Derived images
# (Utah, ...) add variant context here via the context.d/ drop-in. The path is
# derived from REPO_ROOT at call time so it follows REPO_ROOT when tests point
# the module at a throwaway tree instead of the real checkout.
ON_DEVICE_SCOPE = "on-device"


def _agent_bundle_dir() -> Path:
    return REPO_ROOT / "system_files/shared/usr/share/ublue-os/agent"


def _bundle_index_path() -> Path:
    return _agent_bundle_dir() / "index.json"


def _bundle_skills_dir() -> Path:
    return _agent_bundle_dir() / "skills"

# Banner prepended to every shipped skill copy. It is an HTML comment so it is
# invisible in rendered markdown and never breaks the skill's YAML front matter,
# but it flags the repo-only steps that assume a source checkout.
ON_DEVICE_BANNER = (
    "<!-- ON-DEVICE EDITION. Generated from {src} by\n"
    "scripts/generate_skill_index.py --write. Do not edit this file: edit the\n"
    "source skill in docs/skills/ and regenerate the bundle. The root\n"
    "filesystem is read-only on a running machine -- gather evidence and report\n"
    "issues here instead of editing the source checkout. Steps below that edit\n"
    "the source tree assume a checkout, not this image.\n"
    "-->\n\n"
)


def find_skill_files() -> list[Path]:
    """Return every skill's canonical Markdown file, flat and per-directory."""
    files = sorted(p for p in SKILLS_DIR.glob("*.md") if p.name != "index.md")
    files += sorted(SKILLS_DIR.glob("*/SKILL.md"))
    return files


def parse_front_matter(path: Path) -> dict:
    text = path.read_text()
    m = FRONTMATTER_RE.match(text)
    if not m:
        raise ValueError(f"{path}: no YAML front matter found")
    data = yaml.safe_load(m.group(1))
    if not isinstance(data, dict):
        raise ValueError(f"{path}: front matter did not parse to a mapping")
    return data


def build_skill_entry(path: Path) -> dict:
    fm = parse_front_matter(path)
    rel = path.relative_to(REPO_ROOT).as_posix()

    required = [
        "id", "name", "one_line_purpose", "entry_point", "category",
        "status", "tags", "description", "version", "last_updated",
    ]
    missing = [k for k in required if k not in fm]
    if missing:
        raise ValueError(f"{rel}: missing required front-matter key(s): {missing}")
    if fm["name"] != fm["id"]:
        raise ValueError(f"{rel}: name ({fm['name']!r}) does not match id ({fm['id']!r})")

    # Oversized skills are migrated to per-skill directories (write-a-skill.md).
    lines = path.read_text().count("\n")
    if lines > MAX_LINES_HARD:
        raise ValueError(f"{rel} is {lines} lines (hard max {MAX_LINES_HARD})")
    if lines > MAX_LINES_SOFT:
        print(f"warning: {rel} is {lines} lines (soft max {MAX_LINES_SOFT})", file=sys.stderr)

    entry = {
        "id": fm["id"],
        "name": fm["name"],
        "one_line_purpose": fm["one_line_purpose"],
        "entry_point": fm["entry_point"],
        "category": fm["category"],
        "status": fm["status"],
        "tags": fm["tags"],
        "description": " ".join(fm["description"].split()),
        "version": str(fm["version"]),
        "last_updated": str(fm["last_updated"]),
    }
    doc_type = (fm.get("metadata") or {}).get("type")
    if doc_type:
        entry["doc_type"] = doc_type

    if fm["entry_point"] != rel:
        raise ValueError(
            f"{rel}: entry_point front-matter value ({fm['entry_point']!r}) "
            f"does not match actual path ({rel!r})"
        )
    return entry


def build_catalog() -> dict:
    skills = [build_skill_entry(p) for p in find_skill_files()]
    skills.sort(key=lambda s: s["id"])
    return {
        "generated_at": date.today().isoformat(),
        "schema_version": SCHEMA_VERSION,
        "skills": skills,
    }


def on_device_skills() -> list[tuple[Path, str]]:
    """(path, id) for every skill flagged ``scope: on-device`` in front matter.
    These are the subset shipped read-only into every image under
    ``/usr/share/ublue-os/agent/``.
    """
    skills = []
    for path in find_skill_files():
        fm = parse_front_matter(path)
        if fm.get("scope") == ON_DEVICE_SCOPE:
            skills.append((path, fm["id"]))
    return sorted(skills, key=lambda item: item[1])


def _bundle_entry(path: Path, skill_id: str) -> dict:
    fm = parse_front_matter(path)
    return {
        "id": fm["id"],
        "name": fm["name"],
        "one_line_purpose": fm["one_line_purpose"],
        "entry_point": f"skills/{skill_id}.md",
        "description": " ".join(fm["description"].split()),
        "category": fm.get("category"),
        "status": fm.get("status"),
    }


def build_on_device_catalog() -> dict:
    """The shipped on-device catalog: every skill flagged ``scope: on-device``,
    with ``entry_point`` rewritten to the bundle-relative ``skills/<id>.md``.
    """
    skills = sorted(
        (_bundle_entry(p, sid) for p, sid in on_device_skills()),
        key=lambda s: s["id"],
    )
    return {"schema_version": SCHEMA_VERSION, "skills": skills}


def bundle_index_text() -> str:
    return json.dumps(build_on_device_catalog(), indent=2, sort_keys=False) + "\n"


def bundle_skill_text(path: Path, skill_id: str) -> str:
    src = path.relative_to(REPO_ROOT).as_posix()
    text = path.read_text()
    match = FRONTMATTER_RE.match(text)
    if match is None:
        return ON_DEVICE_BANNER.format(src=src) + text
    # Ship the YAML front matter as the first bytes so every skill loader that
    # expects front matter at the top of the copied file still parses it.
    return (
        text[: match.end()]
        + "\n"
        + ON_DEVICE_BANNER.format(src=src)
        + text[match.end():]
    )


def write_bundle() -> None:
    """Write the on-device bundle into system_files/shared/usr/share/ublue-os/agent."""
    catalog = build_on_device_catalog()
    if not catalog["skills"] and not _bundle_skills_dir().exists() and not _bundle_index_path().exists():
        return
    skills_dir = _bundle_skills_dir()
    skills_dir.mkdir(parents=True, exist_ok=True)
    index_path = _bundle_index_path()
    index_path.write_text(bundle_index_text())
    for path, skill_id in on_device_skills():
        (skills_dir / f"{skill_id}.md").write_text(
            bundle_skill_text(path, skill_id)
        )
    # --write should be self-healing: a source skill that lost its
    # `scope: on-device` flag used to leave an orphan copy behind and make
    # --check fail with an error --write could never clear. Drop any copy that
    # is no longer in the catalog.
    expected = {f"{sid}.md" for _, sid in on_device_skills()}
    for stale in skills_dir.iterdir():
        if stale.is_file() and stale.name not in expected:
            stale.unlink()


def check_bundle() -> list[str]:
    """Return drift errors for the on-device bundle.

    ``index.json`` is regenerated from the skill front matter on every run, so
    a byte comparison fails if a skill is flagged ``on-device`` but missing
    from the shipped catalog, or vice versa. Each shipped skill copy is
    compared against its source (plus banner) so an edited skill is caught
    until regenerated. Bundle files are named by skill id so per-skill
    directories (whose canonical file is ``SKILL.md``) never collide.
    """
    errors: list[str] = []
    catalog = build_on_device_catalog()
    if not catalog["skills"] and not _bundle_skills_dir().exists() and not _bundle_index_path().exists():
        return errors

    actual = _bundle_index_path().read_text() if _bundle_index_path().exists() else None
    if actual != bundle_index_text():
        errors.append(
            "error: on-device agent bundle "
            "(system_files/shared/usr/share/ublue-os/agent) is stale. "
            "Run `python3 scripts/generate_skill_index.py --write`."
        )

    expected_files = {f"{e['id']}.md" for e in catalog["skills"]}
    for path, skill_id in on_device_skills():
        bundle_file = _bundle_skills_dir() / f"{skill_id}.md"
        expected = bundle_skill_text(path, skill_id)
        if not bundle_file.exists() or bundle_file.read_text() != expected:
            errors.append(
                f"error: bundle skill {bundle_file.relative_to(REPO_ROOT)} is stale "
                f"(source {path.relative_to(REPO_ROOT)} changed). "
                f"Run `python3 scripts/generate_skill_index.py --write`."
            )

    if _bundle_skills_dir().exists():
        present = {p.name for p in _bundle_skills_dir().iterdir() if p.is_file()}
        extra = present - expected_files
        if extra:
            errors.append(
                f"error: bundle/skills/ has files not in the on-device catalog: {sorted(extra)}"
            )
    return errors


def load_existing_catalog() -> dict | None:
    """Return the currently committed catalog, or None if it doesn't exist/parse."""
    if not INDEX_PATH.exists():
        return None
    try:
        return json.loads(INDEX_PATH.read_text())
    except json.JSONDecodeError:
        return None


def pin_unchanged_generated_at(catalog: dict, existing: dict | None) -> None:
    """Reuse the committed `generated_at` when the actual catalog content
    (schema_version + skills) hasn't changed.

    `generated_at` is a "last regenerated" timestamp, not build-time metadata:
    it should only advance when a skill doc actually changes. Without this,
    every run stamps today's date, which makes `--check` fail on pure
    calendar drift (e.g. a PR branch cut before today, or CI running a day
    after the last regeneration) even though no skill content is stale.
    """
    if (
        existing is not None
        and existing.get("schema_version") == catalog["schema_version"]
        and existing.get("skills") == catalog["skills"]
    ):
        catalog["generated_at"] = existing.get("generated_at", catalog["generated_at"])


def validate_catalog(catalog: dict) -> None:
    schema = json.loads(SCHEMA_PATH.read_text())
    validator = Draft202012Validator(schema)
    errors = sorted(validator.iter_errors(catalog), key=lambda e: e.path)
    if errors:
        for e in errors:
            loc = "/".join(str(p) for p in e.path) or "<root>"
            print(f"schema error at {loc}: {e.message}", file=sys.stderr)
        raise SystemExit(1)


def render_markdown(catalog: dict) -> str:
    lines = [
        "# Skill catalog (generated)",
        "",
        "This file is a human-readable mirror of `index.json`. Both are generated by",
        "`scripts/generate_skill_index.py` — do not hand-edit either file.",
        "",
        f"Generated: {catalog['generated_at']} · schema {catalog['schema_version']} · "
        f"{len(catalog['skills'])} skills",
        "",
        "| id | category | status | one-line purpose |",
        "|---|---|---|---|",
    ]
    for s in catalog["skills"]:
        rel_link = s["entry_point"].removeprefix("docs/skills/")
        lines.append(
            f"| [{s['id']}]({rel_link}) | {s['category']} | {s['status']} | "
            f"{s['one_line_purpose']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="Regenerate index.json and index.md")
    group.add_argument("--check", action="store_true", help="Verify index.json/index.md are up to date")
    args = parser.parse_args()

    try:
        catalog = build_catalog()
        pin_unchanged_generated_at(catalog, load_existing_catalog())
        validate_catalog(catalog)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    json_text = json.dumps(catalog, indent=2, sort_keys=False) + "\n"
    md_text = render_markdown(catalog)

    if args.write:
        INDEX_PATH.write_text(json_text)
        (SKILLS_DIR / "index.md").write_text(md_text)
        write_bundle()
        print(f"wrote {INDEX_PATH.relative_to(REPO_ROOT)} and index.md "
              f"({len(catalog['skills'])} skills)")
        return 0

    # --check
    ok = True
    if not INDEX_PATH.exists() or INDEX_PATH.read_text() != json_text:
        print("error: docs/skills/index.json is stale. Run "
              "`python3 scripts/generate_skill_index.py --write`.", file=sys.stderr)
        ok = False
    md_path = SKILLS_DIR / "index.md"
    if not md_path.exists() or md_path.read_text() != md_text:
        print("error: docs/skills/index.md is stale. Run "
              "`python3 scripts/generate_skill_index.py --write`.", file=sys.stderr)
        ok = False
    for message in check_bundle():
        print(message, file=sys.stderr)
        ok = False
    if not ok:
        return 1
    print(f"docs/skills/index.json and index.md are up to date "
          f"({len(catalog['skills'])} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
